"""Figure 6: vendor-toolchain int8 results (task MAE and induced output bias).

Numbers are transcribed from npu_quant/out/paired_stats.md (machine-generated by
npu_quant/paired_stats.py); only the model order is a choice made here.
"""
from __future__ import annotations

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

MODELS = ["ReLU-QAT\nN=1", "ReLU-QAT\nN=20", "GELU\nN=1", "GLU\nN=1"]
FP32 = [0.075599, 0.060487, 0.079308, 0.076025]
FAKE = [0.079808, 0.062922, 0.078453, 0.078032]
SIMU = [0.079433, 0.063871, 0.079295, 0.080258]
# paired per-image differences reported in npu_quant/out/tables.md (mean of per-sample diff)
DM = {"paired": [0.003834, 0.003368, -0.000157, 0.004233]}
BIAS = [0.01710, 0.00259, 0.00098, 0.01439]
BIAS_SE = [0.00187, 0.00156, 0.00197, 0.00214]
# 去掉该模型的平均输出偏置后重算的 ΔMAE（与稿 §5.7 表 8 末列同口径）
DM_DEB = [0.001957, 0.003108, -0.000034, 0.005003]

C_FP, C_FQ, C_SM = "#9aa0a6", "#e8a33d", "#4c72b0"
MINUS = "\u2212"


def fmt(v: float, nd: int = 4) -> str:
    return ("%+.*f" % (nd, v)).replace("-", MINUS)


def main() -> str:
    fig, axes = plt.subplots(1, 2, figsize=(6.6, 2.32),
                             gridspec_kw={"width_ratios": [1.06, 1.0]})
    ax = axes[0]
    x = np.arange(len(MODELS))
    w = 0.26
    ax.bar(x - w, FP32, w, label="FP32 ONNX", color=C_FP, edgecolor="black", linewidth=0.5)
    ax.bar(x, FAKE, w, label="compiler fake-quant", color=C_FQ, edgecolor="black", linewidth=0.5)
    ax.bar(x + w, SIMU, w, label="simulator (int8)", color=C_SM, edgecolor="black", linewidth=0.5)
    ax.set_ylim(0.0, 0.155)
    ax.set_xlim(-0.55, 3.55)
    ax.set_ylabel("task MAE\n(200 test images)")
    ax.set_xticks(x)
    # 配对差写进刻度标签第三行：柱顶不再放文字，四组标注不会互相顶到
    ax.set_xticklabels([f"{m}\n{fmt(v)}" for m, v in zip(MODELS, DM["paired"])], fontsize=7.8)
    ax.legend(fontsize=7.8, loc="upper left", frameon=False, ncol=1, labelspacing=0.28,
              handlelength=1.3, handletextpad=0.45, borderaxespad=0.2)
    ax.set_title("(a) int8 costs up to 0.004 MAE on\ntwo heads, nothing on GELU", fontsize=8.3)
    ax.grid(axis="y", alpha=0.3, lw=0.4)
    ax.set_axisbelow(True)

    ax = axes[1]
    xs = np.arange(len(BIAS))
    b = np.array(BIAS)
    s = np.array(BIAS_SE)
    ax.errorbar(xs, b, yerr=s, fmt="o", ms=4.5, color="#b23b3b", ecolor="#b23b3b",
                elinewidth=1.0, capsize=2.5)
    ax.axhline(0.0, color="#444444", lw=0.9, ls="--")
    for i, (v, e) in enumerate(zip(b, s)):
        if i == 0:
            off = dict(xytext=(7, 0), ha="left", va="center")
        elif i == len(b) - 1:
            off = dict(xytext=(-7, 0), ha="right", va="center")
        else:
            off = dict(xytext=(0, 8), ha="center", va="bottom")
        ax.annotate(f"{fmt(v)}\n({v / e:.1f} SE)", (i, v), textcoords="offset points",
                    fontsize=7.8, **off)
    ax.set_xticks(xs)
    ax.set_xticklabels(MODELS, fontsize=7.8)
    ax.set_xlim(-0.40, len(MODELS) - 0.60)
    ax.set_ylim(-0.0082, 0.0208)
    ax.set_yticks([0.0, 0.005, 0.010, 0.015, 0.020])
    ax.set_ylabel("$\\Delta$ output mean\n(simulator \u2212 FP32)")
    ax.set_title("(b) a systematic output bias\naccounts for part of the cost", fontsize=8.3)
    ax.text(0.02, 0.045, "de-biased $\\Delta$MAE, same order:\n" +
            " / ".join(fmt(v) for v in DM_DEB),
            transform=ax.transAxes, ha="left", va="bottom", fontsize=7.0, color="#555555",
            linespacing=1.4)
    ax.grid(axis="y", alpha=0.3, lw=0.4)
    ax.set_axisbelow(True)

    for a in axes:
        a.tick_params(axis="y", labelsize=8.0)
    fig.tight_layout(pad=0.3, w_pad=0.8)
    out = "drafts/figs/figS8.png"
    # run-level (n = 8) paired intervals for the none arm, read from the csv
    import csv as _csv, statistics as _st, math as _math, io as _io
    _d = {}
    for _r in _csv.DictReader(_io.open("quant_runs/vendor8_runs.csv", encoding="utf-8")):
        if _r.get("status") == "ok" and _r.get("delta"):
            _d.setdefault(_r["endpoint(N)"].strip(), []).append(float(_r["delta"]))
    def _ci(v):
        m = _st.mean(v); se = _st.pstdev(v) / _math.sqrt(len(v)) * _math.sqrt(len(v)/(len(v)-1))
        return m, m - 2.3646 * se, m + 2.3646 * se
    _parts = []
    for _k, _lab in (("1", "N = 1"), ("inf", "N = inf")):
        if _k in _d and len(_d[_k]) >= 3:
            _m, _lo, _hi = _ci(_d[_k])
            _parts.append("%s: %+.4f [%+.4f, %+.4f] (n = %d)" % (_lab, _m, _lo, _hi, len(_d[_k])))
    if _parts:
        _w, _h = fig.get_size_inches()
        fig.set_size_inches(_w, _h * 1.22)
        fig.subplots_adjust(bottom=0.30, top=0.84)
        fig.text(0.5, 0.055, "run level, none arm, 8 seeds",
                 fontsize=7.5, va="bottom", ha="center")
        fig.text(0.5, 0.015, "   ".join(_parts),
                 fontsize=7.5, va="bottom", ha="center")
    fig.savefig(out, dpi=660)
    print(out)
    return out


if __name__ == "__main__":
    main()